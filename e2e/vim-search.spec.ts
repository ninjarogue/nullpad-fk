const refused: ReadonlyArray<readonly [string, string, string]> = [
  ['\\n', '\\n', 'exact'],
  ['\\zs', '\\zs', 'exact'],
  ['\\ze', '\\ze', 'exact'],
  ['\\&', '\\&', 'exact'],
  ['~', '~', 'exact'],
  ['\\%V', '\\%V', 'contains'],
  ['\\_s', '\\_', 'contains'],
  ['a\\@=', '\\@', 'contains'],
  ['\\(a\\)\\1', '\\1', 'contains'],
  ['[[:alpha:]]', '[:alpha:]', 'contains'],
]

for (const [pattern, token, how] of refused) {
  test(`the token ${token} is refused with a notice and the cursor stays`, async ({
    nullpad,
  }) => {
    await begin(nullpad, noteB)
    await play(nullpad, `/${pattern}<CR>`)
    const notice = await noticeOf(nullpad)
    if (how === 'exact') {
      expect(notice, 'the notice names the token').toBe(
        `not supported in a search: ${token}`,
      )
    } else {
      expect(notice, 'the notice starts as the contract says').toMatch(
        /^not supported in a search: /u,
      )
      expect(notice, 'and names the token').toContain(token)
    }
    await expectUntouched(nullpad, `/${pattern}`, noteB, 1, 1)
  })
}

